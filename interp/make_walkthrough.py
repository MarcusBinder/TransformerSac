("md", r"""
### The residual stream, and where we tap it

The transformer body is **pre-norm**: each sublayer computes its update from
a LayerNorm'd copy of the token vector and then **adds** the result back:

```text
x = x + Attn(LN(x))        # attention sublayer
x = x + MLP(LN(x))         # feed-forward sublayer
```

Because every sublayer only ever *adds* into `x`, the running 128-dim vector
per token is called the **residual stream**. Think of it as a shared
communication bus: the embedding writes the initial content, each sublayer
reads the bus, computes something, and writes its contribution back by
addition, and at the very end the action head reads the bus. Nothing along
the way overwrites — everything accumulates. That additive structure is what
makes the two core operations of this pipeline natural:

- **reading** the stream at any depth is meaningful (it is the sum of
  everything computed so far), and
- **writing** into it (adding a vector) is exactly the kind of edit the
  network's own sublayers perform on every forward pass.

Data flow through this particular actor, with the five capture sites marked
`[...]`:

```text
per-turbine obs (60) ──▶ obs_encoder MLP ─────────────▶ [embed]      (T,128)
wake roses (recep + influ, 360 dirs) ─▶ Fourier enc ─▶ (+) ─▶ profile_embed
[embed] ⧺ profile_embed ──▶ profile_proj (256→128) ──▶ [tok_in]     stream entry
positions (2) ──▶ rel-pos MLP ──▶ attention bias   (enters the attention
                                                    scores, NOT the stream)

[tok_in] ── layer 0: x += Attn(LN(x)); x += MLP(LN(x)) ──▶ [resid_L0]
         ── layer 1:            same                   ──▶ [resid_L1]
[final_norm] = LayerNorm(x) ──▶ fc_mean / fc_logstd ──▶ tanh ──▶ [yaw, derate]
```

| site | what it is | why it matters |
|---|---|---|
| `embed` | obs-encoder output | what a turbine knows from **its own sensors alone** |
| `tok_in` | transformer input | stream entry: obs + wake-geometry profiles fused |
| `resid_L0` | after layer 0 | one round of turbine-to-turbine attention |
| `resid_L1` | after layer 1 | full depth, pre-norm |
| `final_norm` | after the final LayerNorm | what `fc_mean` **directly reads** — the most surgical steering point, since nothing re-normalizes after it |

All sites are `(batch, n_tokens, 128)` tensors; on the 2×2 layout there are
T = 4 tokens per step.
"""),

