aggressive, conservative = y <= lo, y >= hi

v = X[conservative].mean(axis=0) - X[aggressive].mean(axis=0)
v = v / np.linalg.norm(v)
act_std = float((X @ v).std())

stored = np.load(f"{DATA}/directions/direction_final_norm.npz")
print(f"live recompute vs stored artifact: cos = {float(v @ stored['vector']):+.5f}, "
      f"act_std {act_std:.3f} vs {float(stored['act_std']):.3f}")

ridge_w = Ridge(alpha=10.0).fit(X, y).coef_
cos_ridge = float(v @ ridge_w / np.linalg.norm(ridge_w))
print(f"cos(diff-of-means, ridge probe direction) = {cos_ridge:+.3f}")

proj = X @ v
fig, axes = plt.subplots(1, 2, figsize=(11, 3.7))
axes[0].hist(proj[aggressive], bins=40, alpha=0.7, color="C1",
             label="aggressive quartile")
axes[0].hist(proj[conservative], bins=40, alpha=0.7, color="C0",
             label="conservative quartile")
